// Builds lib/locations/antique-barangay-boundaries.ts from the PSA 2023
// barangay boundaries (faeldon/philippines-json-maps, PSGC-coded). OpenStreetMap
// only has scattered barangay points around San Jose, so reverse geocoding
// alone puts most of the town in the wrong barangay.
import { readFile, writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/faeldon/philippines-json-maps/master/2023/geojson/municities/hires";

// PSGC municipality codes 0600601000-0600618000, in the same alphabetical
// order as app/_content/antique-barangays.ts (Dao is Tobias Fornier).
const MUNICIPALITIES = [
  "Anini-y", "Barbaza", "Belison", "Bugasong", "Caluya", "Culasi", "Tobias Fornier", "Hamtic", "Laua-an",
  "Libertad", "Pandan", "Patnongon", "San Jose de Buenavista", "San Remigio", "Sebaste", "Sibalom", "Tibiao", "Valderrama",
];

// PSA spellings that differ from the PSGC names the app and database use.
const PSA_ALIASES = {
  "Barbaza/Lumboyan": "Lombuyan",
  "Bugasong/Centro Ilauod": "Centro Ilawod",
  "Tobias Fornier/Ballescas": "Balloscas",
  "Tobias Fornier/Samalague": "Salamague",
  "Tobias Fornier/Sto. Tomas": "Santo Tomas",
  "Sibalom/Bululacao": "Bulalacao",
  "Tibiao/Sta. Ana": "Santa Ana",
  "Tibiao/Sta. Justa": "Santa Justa",
  "Tibiao/Sto. Rosario": "Santo Rosario",
};

const key = (value) => value.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");
const round = (value) => Math.round(value * 1e5) / 1e5;

const source = await readFile(new URL("../app/_content/antique-barangays.ts", import.meta.url), "utf8");
const official = Object.fromEntries([...source.matchAll(/^  "([^"]+)": \[([\s\S]*?)^  \],?$/gm)].map(([, municipality, body]) => [
  municipality,
  [...body.matchAll(/"([^"]+)"/g)].map(([, barangay]) => barangay),
]));

const boundaries = [];
for (const [index, municipality] of MUNICIPALITIES.entries()) {
  const code = `6006${String(index + 1).padStart(2, "0")}000`;
  const response = await fetch(`${SOURCE}/bgysubmuns-municity-${code}.0.1.json`);
  if (!response.ok) throw new Error(`${municipality}: HTTP ${response.status}`);
  const collection = await response.json();
  const names = official[municipality];
  if (!names) throw new Error(`${municipality} is not in antique-barangays.ts`);

  for (const feature of collection.features) {
    const psaName = feature.properties.adm4_en;
    const wanted = PSA_ALIASES[`${municipality}/${psaName}`] ?? psaName;
    // Exact first: "Bongbongan I-II" and "Bongbongan III" share a loose key.
    const barangay = names.find((name) => name === wanted) ?? names.find((name) => key(name) === key(wanted));
    if (!barangay) throw new Error(`${municipality}: no official barangay for PSA "${psaName}"`);

    const polygons = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    const rings = polygons.map((polygon) => polygon.map((ring) => ring.flatMap(([longitude, latitude]) => [round(longitude), round(latitude)])));
    const all = rings.flat(2);
    const longitudes = all.filter((_, i) => i % 2 === 0);
    const latitudes = all.filter((_, i) => i % 2 === 1);
    boundaries.push([
      municipality, barangay,
      [Math.min(...longitudes), Math.min(...latitudes), Math.max(...longitudes), Math.max(...latitudes)],
      rings,
    ]);
  }
  const covered = new Set(boundaries.filter(([m]) => m === municipality).map(([, b]) => b));
  const missing = names.filter((name) => !covered.has(name));
  if (missing.length) throw new Error(`${municipality}: no boundary for ${missing.join(", ")}`);
}

const output = `// Generated by scripts/build-antique-barangay-boundaries.mjs from the PSA 2023
// barangay boundaries. Do not edit by hand.
// Each entry: [municipality, barangay, [west, south, east, north], polygons].
// A polygon is a list of rings; a ring is a flat [lon, lat, lon, lat, ...] list.

export type BarangayBoundary = [string, string, [number, number, number, number], number[][][]];

export const ANTIQUE_BARANGAY_BOUNDARIES: BarangayBoundary[] = JSON.parse(${JSON.stringify(JSON.stringify(boundaries))});
`;
await writeFile(new URL("../lib/locations/antique-barangay-boundaries.ts", import.meta.url), output);
console.log(`Wrote ${boundaries.length} barangay boundaries.`);
